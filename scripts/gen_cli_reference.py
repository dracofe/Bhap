"""Regenerate docs/cli-reference.md from the real argparse tree: python scripts/gen_cli_reference.py"""
import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
os.environ["COLUMNS"] = "100"

from bhap.cli import build_parser  # noqa: E402
from bhap.i18n import set_language  # noqa: E402

set_language("en")
parser = build_parser()
lines = ["# CLI reference", "", "_Generated by `scripts/gen_cli_reference.py` — do not edit by hand._", "",
         "Bare `bhap` (or `bhap chat`) opens the interactive session; type `/help` inside it.", "",
         "Global options (accepted anywhere on the command line): `-w/--workspace`, `--lang id|en`, `--no-color`, "
         "`-q/--quiet`. Environment: `BHAP_HOME`, `BHAP_LANG`, `BHAP_OLLAMA_URL`, `BHAP_LLAMACPP_URL`, `NO_COLOR`, "
         "`BHAP_BACKUP_PASSPHRASE`.", "", "```text", parser.format_help().rstrip(), "```", ""]
sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
seen = set()
for name, child in sub.choices.items():
    if id(child) in seen:
        continue
    seen.add(id(child))
    lines += [f"## bhap {name}", "", "```text", child.format_help().rstrip(), "```", ""]
(ROOT / "docs" / "cli-reference.md").write_text("\n".join(lines), encoding="utf-8")
print("wrote docs/cli-reference.md")
